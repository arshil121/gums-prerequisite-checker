    // Banner for the CSE 400a credit threshold — always visible on Summary so
    // the advisor sees the shortfall before they even try to add the course.
    function creditGateHTML(totalCredits) {
      const rule = SPECIAL_RULES[CREDIT_GATE_COURSE];
      if (!rule || !rule.minCredits) return '';
      const required = rule.minCredits;
      const met = totalCredits >= required;
      const shortfall = Math.max(0, required - totalCredits);
      const pct = Math.max(0, Math.min(100, (totalCredits / required) * 100));
      const selectedGate = state.selectedCourses.some(sc =>
        StorageManager.normalize(sc.courseCode) === CREDIT_GATE_COURSE);

      const selectedWarning = (!met && selectedGate)
        ? `<div style="margin-top:8px;font-weight:bold;">⛔ CSE 400a is selected this term but the credit requirement is not met — this registration should not go through.</div>`
        : '';

      return `
        <div class="gums-credit-gate ${met ? 'ok' : 'bad'}">
          <div class="gums-credit-gate-head">
            ${met ? '✓' : '✗'} CSE 400a · minimum ${required} credits
            <span class="gums-badge ${met ? 'eligible' : 'ineligible'}">${met ? 'ELIGIBLE' : 'NOT ELIGIBLE'}</span>
          </div>
          <div class="gums-credit-gate-bar"><span style="width:${pct.toFixed(1)}%"></span></div>
          <div class="gums-credit-gate-note">
            Completed <b>${totalCredits.toFixed(1)}</b> of <b>${required}</b> credits${met
              ? ' — the student may register for CSE 400a.'
              : ` — <b>${shortfall.toFixed(1)}</b> more credit(s) needed before CSE 400a can be taken.`}
          </div>
          ${selectedWarning}
        </div>`;
    }

